import { expect, test } from "@playwright/test";

for (const dateFormat of ["dd/MM/yyyy", "yyyy-MM-dd"]) {
  test(`edits and persists the license start year using ${dateFormat}`, async ({ page }) => {
    await page.goto("/login");
    await page.getByRole("button", { name: "Try the demo" }).click();
    await expect(page.getByRole("button", { name: "Logout" })).toBeVisible({ timeout: 30_000 });
    const headers = { Origin: "http://127.0.0.1:3000" };
    const preferences = await page.request.patch("/api/profile", { headers, data: { action: "preferences", preferences: { dateFormat } } });
    expect(preferences.ok(), await preferences.text()).toBeTruthy();
    const selected = await page.request.patch("/api/compliance", { headers, data: { action: "select-license", licenseId: "ch-hochseeausweis-sail", selected: true } });
    expect(selected.ok(), await selected.text()).toBeTruthy();
    const logbook = await (await page.request.get("/api/logbook")).json();
    expect(logbook.boats.every((boat: { type: string }) => ["sail", "motor"].includes(boat.type))).toBe(true);
    await page.reload();
    await page.getByRole("button", { name: "Compliance", exact: true }).click();
    const input = page.locator('input[type="text"][id="license-start-ch-hochseeausweis-sail"]');
    await expect(input).toBeVisible();
    const achieved = page.locator(".requirement-progress dl > div:first-child dd");
    await expect(achieved).toHaveCount(3);
    await expect(achieved).toHaveText(["0", "0", "0"]);
    await expect(input).toHaveAttribute("aria-label", "Theory exam date");
    const manualDetails = page.locator("#requirement-copy-ch-7-a-2-2");
    await expect(manualDetails).toContainText("700 nautical miles");
    await expect(manualDetails).toContainText("4 years after the reference date");
    await expect(manualDetails).toContainText("Boat type");
    await page.setViewportSize({ width: 375, height: 812 });
    await expect(manualDetails).toBeVisible();
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.setViewportSize({ width: 1280, height: 720 });
    const handwrittenLogbook = page.locator(".tracked-license").first().getByRole("checkbox", { name: "Handwritten logbook for voyages counted toward the license", exact: true });
    await expect(handwrittenLogbook).not.toBeChecked();
    await handwrittenLogbook.click();
    await expect(handwrittenLogbook).toBeChecked();
    await expect.poll(async () => (await (await page.request.get("/api/compliance")).json()).licenses[0].completedManualRequirementIds).toContain("ch-hochseeausweis-sail-handwritten-logbook");
    const saves: string[] = [];
    page.on("request", request => {
      if (request.url().endsWith("/api/compliance") && request.method() === "PATCH") saves.push(request.postData() ?? "");
    });
    const date = dateFormat === "yyyy-MM-dd" ? "2026-04-02" : "02/04/2026";
    await input.pressSequentially(date);
    await expect(input).toBeFocused();
    expect(saves).toHaveLength(0);
    await input.press("Enter");
    await expect.poll(async () => (await (await page.request.get("/api/compliance")).json()).licenses[0].startDate).toBe("2026-04-02");
    await expect(input).toBeEnabled();
    await input.fill(dateFormat === "yyyy-MM-dd" ? "2025-04-02" : "02/04/2025");
    await input.press("Tab");
    await expect.poll(async () => (await (await page.request.get("/api/compliance")).json()).licenses[0].startDate).toBe("2025-04-02");
    await page.reload();
    await expect(input).toHaveValue(dateFormat === "yyyy-MM-dd" ? "2025-04-02" : "02/04/2025");
    await expect(handwrittenLogbook).toBeChecked();
    await input.fill("invalid");
    await input.press("Tab");
    await expect(input).toHaveAttribute("aria-invalid", "true");
    await input.fill("");
    await input.press("Tab");
    await expect.poll(async () => (await (await page.request.get("/api/compliance")).json()).licenses[0].startDate).toBeNull();
    const picker = page.locator('input[type="date"]').first();
    await picker.fill("2024-03-01");
    await picker.press("Enter");
    await expect.poll(async () => (await (await page.request.get("/api/compliance")).json()).licenses[0].startDate).toBe("2024-03-01");
    await input.fill(dateFormat === "yyyy-MM-dd" ? "2021-07-01" : "01/07/2021");
    await input.press("Enter");
    await expect.poll(async () => (await (await page.request.get("/api/compliance")).json()).licenses[0].startDate).toBe("2021-07-01");
    // The demo sailing cruise is in September 2025: the entire final year now counts.
    await expect(achieved).toHaveText(["4", "4", "87.8"]);
    await expect(manualDetails).toContainText(dateFormat === "yyyy-MM-dd" ? "2021-07-01 – 2025-12-31" : "01/07/2021 – 31/12/2025");
    await page.reload();
    // The demo sailing cruise is in September 2025: the entire final year now counts.
    await expect(achieved).toHaveText(["4", "4", "87.8"]);
    await expect(page.locator("#requirement-copy-ch-7-a-2-1")).toContainText(dateFormat === "yyyy-MM-dd" ? "2017-01-01 – 2025-12-31" : "01/01/2017 – 31/12/2025");
    await page.locator("#compliance-license").selectOption("ch-hochseeausweis-sail-addon");
    const extensionDate = page.locator("#license-start-ch-hochseeausweis-sail-addon");
    await expect(extensionDate).toHaveAttribute("aria-label", "Extension application date");
    await expect(page.locator(".tracked-license").nth(1).getByRole("checkbox", { name: "Handwritten logbook for voyages counted toward the license", exact: true })).not.toBeChecked();
    await extensionDate.fill(dateFormat === "yyyy-MM-dd" ? "2021-07-01" : "01/07/2021");
    await extensionDate.press("Enter");
    await expect(page.locator("#requirement-copy-ch-8-a-2")).toContainText(dateFormat === "yyyy-MM-dd" ? "2017-01-01 – 2021-07-01" : "01/01/2017 – 01/07/2021");
  });
}
